#!/bin/sh
# Regenerate internal/resume/testdata from the real trainer plus the reference writer.
#
#   sh hack/gen-resume-fixtures.sh
#
# Every checkpoint here is produced by cmd/ckpttrainer --contract, so the shards, the manifest and the
# sealed ordering are what a real writer leaves. The only file this script authors is resume.json, and
# it goes through internal/resume.Write. Two fixtures are deliberately damaged after the fact, the way a
# kill damages them: `invalid` is a truncated declaration, and `unknown-format` is a writer that invented
# a format (written without validation on purpose).
#
# The generated trees are checked in and must not be edited by hand: the test in
# internal/resume/fixtures_test.go rebuilds them and compares byte for byte.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/internal/resume/testdata"
GO=${GO:-go}
STEPS=513   # one final checkpoint at step 512, and no earlier write
SHARD=32

cd "$ROOT"

# train <fixture> [trainer flags...] -> prints the generation directory
train() {
	name=$1
	shift
	rm -rf "$OUT/$name"
	mkdir -p "$OUT/$name"
	"$GO" run ./cmd/ckpttrainer --dir="$OUT/$name" --steps="$STEPS" --step-ms=0 \
		--write-ms=0 --shard-bytes="$SHARD" --ranks=2 --contract "$@" >/dev/null

	# The trainer writes exactly one generation; anything else means the fixture is not what it claims.
	set -- "$OUT/$name"/gen-*
	if [ ! -d "$1" ] || [ -e "${2:-}" ]; then
		echo "expected exactly one generation directory in $OUT/$name" >&2
		exit 1
	fi
	printf '%s' "$1"
}

declare() { # declare <fixture> <profile> <verdict line>
	gen=$(train "$1")
	"$GO" run hack/gen-resume-fixtures.go -gen="$gen" -profile="$2" >/dev/null
	write_readme "$1" "$3"
}

write_readme() {
	printf '%s\n' "# $1" "" "$2" "" \
		"Generated by \`sh hack/gen-resume-fixtures.sh\`; do not edit. The shards and the manifest" \
		"come from \`ckpttrainer --contract\` (one generation, step 512), the declaration from" \
		"\`internal/resume.Write\`." >"$OUT/$1/README.md"
}

# --- the static fixtures ---------------------------------------------------------------
declare full "full" \
	"Every state a full restore needs, world 8 unchanged: **resumable**."
declare weights-only "weights-only" \
	"Model only — the library's \`save_only_model\` default: **not resumable: optimizer state absent**."
declare partial-optimizer "partial-optimizer" \
	"The file holds the optimizer and the loader is told to skip it: **not resumable: declared partial (optimizer)**."
declare reshardable "reshardable" \
	"World 8, declared reshardable: **resumable with resharding** against a world of 16."
declare unknown-format "unknown-format" \
	"A writer that invented a format: **unknown: format \"nemo\" is not one we can judge**."

# --- sealed but silent ------------------------------------------------------------------
gen=$(train no-resume)
write_readme no-resume "Manifest sealed, no declaration: **unknown: sealed, but nobody said what it holds**."

# --- a declaration killed mid-write -----------------------------------------------------
gen=$(train invalid)
"$GO" run hack/gen-resume-fixtures.go -gen="$gen" -profile=full >/dev/null
# A kill between two writes leaves a prefix. A reader must tell that from a shorter valid file.
head -c 24 "$gen/resume.json" >"$gen/.resume.partial"
mv "$gen/.resume.partial" "$gen/resume.json"
write_readme invalid "A declaration truncated mid-write: **unknown: resume.json does not parse**."

echo "resume fixtures: $(ls -d "$OUT"/*/ | wc -l) directories"
